#!/bin/bash
# Builds "Space Hunter.app" on a Mac (a universal app: Apple silicon + Intel).
# Needs Xcode or the Command Line Tools (xcode-select --install).
# Usage:  cd mac && chmod +x build.sh && ./build.sh
# The fonts come from ../fonts, the cleanup items from cleaners.json and the version number from ../VERSION.
set -euo pipefail
cd "$(dirname "$0")"

APP="build/Space Hunter.app"
rm -rf build
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources/fonts" build/obj
VERSION="$(tr -d '[:space:]' < ../VERSION)"
printf '// Generated by build.sh from ../VERSION. Do not edit.
enum AppVersion { static let text = "%s" }
' "$VERSION" > build/obj/Version.swift

for ARCH in arm64 x86_64; do
  swiftc -O -parse-as-library -target "${ARCH}-apple-macos13.0" \
    -o "build/obj/SpaceHunter-${ARCH}" Sources/SpaceHunter.swift build/obj/Version.swift
done
lipo -create build/obj/SpaceHunter-arm64 build/obj/SpaceHunter-x86_64 -output "$APP/Contents/MacOS/SpaceHunter"

cp ../fonts/*.ttf ../fonts/OFL.txt "$APP/Contents/Resources/fonts/"
cp cleaners.json "$APP/Contents/Resources/"
if [ -d assets/AppIcon.iconset ]; then
  iconutil -c icns assets/AppIcon.iconset -o "$APP/Contents/Resources/AppIcon.icns"
fi

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>Space Hunter</string>
  <key>CFBundleDisplayName</key><string>Space Hunter</string>
  <key>CFBundleIdentifier</key><string>io.github.knox-101.spacehunter</string>
  <key>CFBundleExecutable</key><string>SpaceHunter</string>
  <key>CFBundleIconFile</key><string>AppIcon</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>${VERSION}</string>
  <key>CFBundleVersion</key><string>${VERSION}</string>
  <key>NSHumanReadableCopyright</key><string>Copyright (c) 2026 Blesson Reji (knox-101)</string>
  <key>LSMinimumSystemVersion</key><string>13.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

# Ad-hoc signature so macOS runs it (not notarized: first launch needs right-click > Open).
codesign --force --deep -s - "$APP"
echo "Built $APP (version $VERSION)"
echo "First launch: right-click the app > Open. For the Trash and some caches, add it under"
echo "System Settings > Privacy & Security > Full Disk Access."
